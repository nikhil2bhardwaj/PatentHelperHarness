import time
from typing import Optional

from rich.console import Console

from harness.config import PHASE_NAMES

console = Console()


class MockAPIClient:
    """Drop-in replacement for APIClient that returns simulated responses.
    Useful for testing the full workflow without an OpenAI API key.
    """

    def __init__(
        self,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ):
        self.model = model or "mock-model"
        self.temperature = temperature or 0.7
        self.max_tokens = max_tokens or 4096

    def chat(self, system_prompt: str, user_prompt: str, json_mode: bool = False) -> str:
        console.print("[dim][MOCK] Simulating API response...[/dim]")
        time.sleep(1.8)

        # Try to determine which phase this is from the user_prompt
        phase = self._detect_phase(user_prompt)
        phase_name = PHASE_NAMES.get(phase, "Unknown")

        if json_mode:
            return self._generate_json_response(phase, phase_name)
        else:
            return self._generate_markdown_response(phase, phase_name)

    def _detect_phase(self, user_prompt: str) -> int:
        for phase in range(13):
            marker = f"PHASE {phase}"
            if marker in user_prompt.upper():
                return phase
        # Check for phase-specific keywords
        if "User Intent" in user_prompt or "USER_INPUT" in user_prompt:
            return 0
        return 0

    def _generate_json_response(self, phase: int, phase_name: str) -> str:
        import json

        response = {
            "phase": phase,
            "phase_name": phase_name,
            "status": "simulated",
            "note": "This is a MOCK response for testing. No OpenAI API was called.",
            "summary": f"[MOCK] Phase {phase} ({phase_name}) simulated output. Replace with real API to get actual analysis.",
            "inputs_for_next_phase": {
                "note": "Simulated handoff data for next phase.",
                "key_points": ["Mock point 1", "Mock point 2", "Mock point 3"],
            },
            "decision": {
                "final_path": f"Proceed to Phase {phase + 1}" if phase < 12 else "Workflow complete",
            },
        }
        return json.dumps(response, indent=2, ensure_ascii=False)

    def _generate_markdown_response(self, phase: int, phase_name: str) -> str:
        return f"""# PHASE {phase}: {phase_name}

> **[MOCK RESPONSE]** — This is a simulated output for testing. No OpenAI API was called.

## Summary
This is a mock response for Phase {phase} ({phase_name}). The actual analysis would be generated by the OpenAI API.

## Key Findings (Mock)
- Mock finding 1
- Mock finding 2
- Mock finding 3

## Inputs for Phase {phase + 1}
- Mock handoff data 1
- Mock handoff data 2

## Phase {phase} Decision
- **Final Path:** {"Proceed to Phase " + str(phase + 1) if phase < 12 else "Workflow complete"}
"""
